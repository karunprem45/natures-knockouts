"""T3 write-up: Evo 2 on coding variants vs lead tags. Post-freeze extension, not pre-registered.

  python -m exploratory.evo2_coding.analyze     -> exploratory/evo2_coding/RESULTS.md
"""
import json, re
from pathlib import Path
import numpy as np
import pandas as pd
import config
from eval import metrics as m

ROOT = config.ROOT
HERE = Path(__file__).resolve().parent
FR = ROOT / "frozen_results"


def scores(path, idx):
    return pd.read_csv(path / "scores.csv").set_index("gene_code")["score"].reindex(idx).values.astype(float)


def fmtd(t):
    return f"{t[0]:+.3f} ({t[1]:+.3f}, {t[2]:+.3f})"


def usage(run):
    asked = answered = 0
    for line in (run / "board.jsonl").read_text().splitlines():
        a = json.loads(line)
        if a["round"] == 0:
            asked += sum(n["type"] == "variant_check" for n in a["needs"])
        if a["producer_agent"] == "variant" and a["artifact_type"] == "fulfillment":
            answered += 1
    return asked, answered


def main():
    lab = pd.read_csv(config.LABELS_DIR / "panel_labels.csv").set_index("gene_code").sort_index()
    y, idx = lab["label"].values, lab.index
    a3 = scores(FR / "runs" / "A3_s1", idx)
    lead = scores(FR / "exploratory" / "runs" / "A3_variant_s1", idx)
    coding = scores(HERE / "A3_variant_coding_s1", idx)
    d_coding = m.paired_delta(m.auroc, y, coding, a3)
    d_lead = m.paired_delta(m.auroc, y, lead, a3)
    d_vs_lead = m.paired_delta(m.auroc, y, coding, lead)
    floor = float(re.search(r"Measured noise floor:\s+([0-9.]+)", (ROOT / "exploratory/noise_floor/RESULTS.md").read_text()).group(1))

    sc = pd.read_csv(HERE / "scores.csv")
    ok = sc[sc.ok == 1]
    pct = ok.site_percentile.dropna()
    summary = json.loads((HERE / "gene_summary.json").read_text())
    pos_codes = set(lab.index[lab.label == 1])
    med = lambda codes: float(np.median([summary[c]["median_site_percentile"] for c in codes
                                         if summary[c]["median_site_percentile"] is not None]))
    asked, answered = usage(HERE / "A3_variant_coding_s1")
    log = [json.loads(l) for l in (HERE / "A3_variant_coding_s1" / "llm_log.jsonl").read_text().splitlines()]
    calls = [l for l in log if "prompt_tokens" in l]

    holds = d_coding[0] > 0.038
    real = d_coding[0] > floor
    verdict = ("Supported, and above the noise floor" if holds and real else
               "Point estimate above +0.038 but within the noise floor: not established" if holds else
               "Not supported")

    text = "\n".join([
        "# T3: Evo 2 on coding variants",
        "",
        "**Post-freeze extension, not pre-registered in frozen/.** The prediction was committed before any variant "
        "was collected or scored ([`PREDICTION.md`](PREDICTION.md)). Evo 2 ran on NVIDIA's hosted 40B endpoint "
        "(`/forward`, `unembed`); Brev was not used. Generated by `exploratory/evo2_coding/analyze.py`.",
        "",
        "## The variants",
        "",
        f"{len(sc)} predicted loss-of-function variants from Ensembl, 5 per gene for all 40 genes "
        f"({', '.join(f'{k} {v}' for k, v in sc.consequence.value_counts().items())}). Scored: {len(ok)}; "
        f"reference-base mismatches or other errors: {len(sc) - len(ok)}.",
        "",
        f"Median site percentile of the scored substitutions: **{pct.median():.1f}** (GWAS lead variants: 59). "
        f"Share below the 10th percentile: {(pct < 10).mean():.2f}. Median of per-gene medians: known targets "
        f"{med(pos_codes):.1f}, negatives {med(set(idx) - pos_codes):.1f}.",
        "",
        "## The Variant arm (A3 + Variant, seed 1)",
        "",
        "| Input to the Variant agent | Paired Δ AUROC vs A3 seed 1 (95% CI) |",
        "| --- | --- |",
        f"| GWAS lead tags (existing run, seed 1) | {fmtd(d_lead)} |",
        "| GWAS lead tags (existing, 2 seeds) | +0.038, CI includes zero |",
        f"| **Coding loss-of-function variants (new)** | **{fmtd(d_coding)}** |",
        "",
        f"Coding − lead-tag run, same seed: {fmtd(d_vs_lead)}. Agents raised {asked} variant_check needs and the "
        f"Variant agent answered {answered}. {len(calls)} LLM calls, ${sum(l.get('cost_usd') or 0 for l in calls):.2f}.",
        "",
        f"## Verdict on the prediction: {verdict}",
        "",
        f"Prediction: the Variant channel contributes more than +0.038. Measured: {d_coding[0]:+.3f}. Noise floor "
        f"(T1, 5 replicates): {floor:.3f}; this contrast is {abs(d_coding[0]) / floor:.1f}× the floor.",
        "",
        "**What this says about the diagnosis.** The coding variants were far more disruptive to Evo 2 than the lead "
        f"tags (median percentile {pct.median():.1f} vs 59), so the earlier diagnosis was right at the DNA level. But "
        f"they were about equally disruptive in known targets ({med(pos_codes):.1f}) and in negatives "
        f"({med(set(idx) - pos_codes):.1f}). Evo 2 measures whether a variant breaks the gene, not whether breaking "
        "it is good for the carrier, and only the second separates targets from negatives here. Every panel gene was "
        "chosen for having protective loss-of-function burden evidence, so near-universal disruption carries no "
        "ranking information. Better variants were necessary but not sufficient.",
        "",
        "**Why the channel stays small by design.** The Variant agent only answers needs in round 1; its answers "
        "reach the score only through other agents' revisions in round 2, inside the same 10-call budget. So even "
        "perfect DNA-level evidence moves AUROC only indirectly. The coding variants do look far more disruptive "
        "to Evo 2 than the lead tags did; whether that reaches the ranking is what the table above measures.",
        "",
    ])
    (HERE / "RESULTS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
