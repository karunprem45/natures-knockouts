"""T1: noise floor from 5 replicates of A3. Post-freeze extension, not pre-registered.

  python -m exploratory.noise_floor.analyze

Replicates: seeds 1-2 (frozen_results/runs/A3_s1, A3_s2, read only) and seeds 3-5 (exploratory/noise_floor/A3_s*),
all A3 with identical settings except the seed. Writes RESULTS.md and effects_vs_floor.md here.
"""
import itertools, json
from pathlib import Path
import numpy as np
import pandas as pd
import config
import scoring
from arms.rescore import ABLATIONS
from board.artifact import Artifact
from eval import metrics as m

ROOT = config.ROOT
HERE = Path(__file__).resolve().parent
RUNS = {1: ROOT / "frozen_results/runs/A3_s1", 2: ROOT / "frozen_results/runs/A3_s2",
        3: HERE / "A3_s3", 4: HERE / "A3_s4", 5: HERE / "A3_s5"}


def boards(run):
    if (run / "genes").exists():
        out = {}
        for p in sorted((run / "genes").glob("Gene_*.json")):
            rec = json.loads(p.read_text())
            out[rec["gene_code"]] = [Artifact.from_dict(a) for a in rec["artifacts"]]
        return out
    out = {}
    for line in (run / "board.jsonl").read_text().splitlines():
        a = Artifact.from_dict(json.loads(line))
        out.setdefault(a.gene_code, []).append(a)
    return out


def main():
    lab = pd.read_csv(config.LABELS_DIR / "panel_labels.csv").set_index("gene_code").sort_index()
    y = lab["label"].values
    reps = {s: r for s, r in RUNS.items() if (r / "scores.csv").exists()
            and len(pd.read_csv(r / "scores.csv")) == len(lab)}
    au, pen, r0 = {}, {}, {}
    for s, r in reps.items():
        sc = pd.read_csv(r / "scores.csv").set_index("gene_code")["score"].reindex(lab.index).values
        b = boards(r)
        iso = pd.Series({c: scoring.score(ABLATIONS["isolated"](a)) for c, a in b.items()}).reindex(lab.index).values
        au[s], r0[s] = m.auroc(y, sc), m.auroc(y, iso)
        pen[s] = au[s] - r0[s]
    diffs = [abs(au[a] - au[b]) for a, b in itertools.combinations(sorted(au), 2)]
    d = np.array(diffs)
    floor = float(np.percentile(d, 95))
    seeds = sorted(au)
    errors = {s: sum(x.artifact_type == "error" for arts in boards(reps[s]).values() for x in arts) for s in seeds}

    res = "\n".join([
        "# Noise floor: 5 replicates of A3",
        "",
        "**Post-freeze extension, not pre-registered.** A3 exactly as pre-registered (same model, prompts, 10-call cap, "
        "scoring); only the seed changes. Seeds 1-2 are the frozen runs (read only); seeds 3-5 were run for this "
        "analysis. Generated by `exploratory/noise_floor/analyze.py`.",
        "",
        "```",
        f"Replicates: {len(seeds)} (seeds {', '.join(map(str, seeds))}), A3, identical settings",
        f"AUROC per replicate:        [{', '.join(f'{au[s]:.3f}' for s in seeds)}]",
        f"Pairwise |ΔAUROC|, n = {len(d)}:  mean {d.mean():.3f}, sd {d.std(ddof=1):.3f}, median {np.median(d):.3f}, "
        f"95th pct {floor:.3f}",
        f"Measured noise floor:       {floor:.3f}  (95th percentile; max pairwise {d.max():.3f})",
        "```",
        "",
        f"Error artifacts per replicate: {', '.join(f'seed {s}: {errors[s]}' for s in seeds)}.",
        "",
        "## The coordination penalty in every replicate",
        "",
        "Each replicate's own board, re-scored round 0 only with the unchanged `scoring.py`, gives an independent "
        "measurement of the coordination penalty (A3 − round 0).",
        "",
        "| Seed | A3 AUROC | Round 0 AUROC | A3 − round 0 |",
        "| --- | --- | --- | --- |",
        *[f"| {s} | {au[s]:.3f} | {r0[s]:.3f} | {pen[s]:+.3f} |" for s in seeds],
        "",
        f"Penalty across replicates: mean {np.mean(list(pen.values())):+.3f}, sd {np.std(list(pen.values()), ddof=1):.3f}, "
        f"negative in {sum(v < 0 for v in pen.values())} of {len(pen)}. If the loop had no effect, each replicate would "
        f"be equally likely to go either way; all {len(pen)} negative has one-sided sign-test probability "
        f"1/{2 ** len(pen)} = {0.5 ** len(pen):.3f}.",
        "",
        "**What changed versus what we said before.** The earlier ~0.03 floor came from one accidental pair of runs; "
        f"measured over {len(d)} pairs it is {floor:.3f}, about twice as large. Against it the frozen coordination "
        f"penalty (0.071) is only {0.071 / floor:.1f}× the floor. The penalty's sign, however, replicates in every run, "
        f"and its size across replicates (mean {abs(np.mean(list(pen.values()))):.3f}) is smaller than the frozen seeds "
        "suggested.",
        "",
        "With 10 pairwise differences, the 95th percentile sits close to the maximum, so this floor is deliberately "
        "conservative.",
        "",
    ])
    (HERE / "RESULTS.md").write_text(res)

    a2c = ROOT / "exploratory/A2_constrained/scores.csv"
    effects = [
        ("Coordination penalty (A3 − round 0), frozen seeds 1-2", 0.071, "paired, same boards"),
        ("Coordination penalty, mean over all replicates", abs(float(np.mean(list(pen.values())))), "paired, same boards"),
        ("Multi-agent vs single (round 0 − A1)", 0.080, "different runs"),
        ("Evo 2 Variant channel (A3 + Variant − A3)", 0.038, "different runs"),
        ("Calibrated skeptic on panel 2 (calibrated − flat)", 0.004, "paired, same board"),
    ]
    lines = ["# Every reported effect against the measured noise floor", "",
             f"**Post-freeze extension, not pre-registered.** Floor = {floor:.3f} AUROC, the 95th percentile of the "
             f"{len(d)} pairwise differences between {len(seeds)} replicates of A3 (`RESULTS.md`).", "",
             "| Effect | Size | × floor | Above floor? | Comparison type |", "| --- | --- | --- | --- | --- |"]
    for name, size, kind in effects:
        lines.append(f"| {name} | {size:.3f} | {size / floor:.1f}× | {'yes' if size > floor else 'no'} | {kind} |")
    if a2c.exists():
        a2 = pd.read_csv(a2c).set_index("gene_code")["score"].reindex(lab.index).values
        r0s1 = pd.read_csv(ROOT / "frozen_results/runs/A3_isolated_s1/scores.csv").set_index("gene_code")["score"].reindex(lab.index).values
        size = abs(m.auroc(y, a2) - m.auroc(y, r0s1))
        lines.append(f"| A2-constrained vs round 0 (seed 1) | {size:.3f} | {size / floor:.1f}× | "
                     f"{'yes' if size > floor else 'no'} | different runs |")
    lines.append(f"| Coordination penalty sign across replicates | {sum(v < 0 for v in pen.values())}/{len(pen)} negative | — | "
                 f"sign test p = {0.5 ** len(pen):.3f} | paired, each replicate |")
    lines += ["",
              "**How to read the comparison type.** The floor is the spread between whole reruns of one arm, so it is the "
              "right yardstick for contrasts between different runs (round 0 − A1, the Evo 2 run). The coordination "
              "penalty and the calibrated-skeptic contrast re-score the same board two ways, so rerun variation is "
              "largely shared between the two sides; for the penalty, the per-replicate table in `RESULTS.md` is the "
              "more direct test of whether it is real.", ""]
    (HERE / "effects_vs_floor.md").write_text("\n".join(lines))
    print(res)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
