"""Paired analysis of the coordination penalty across the 5 A3 replicates. Post-freeze extension, not pre-registered.

  python -m exploratory.noise_floor.paired     -> exploratory/noise_floor/PAIRED_ANALYSIS.md

Each replicate's penalty is A3 AUROC minus the AUROC of the same board re-scored round 0 only (unchanged
scoring.py), so it is a paired, within-run quantity. Recomputed here from the boards (seeds 1-2 frozen, read
only; seeds 3-5 in exploratory/noise_floor/), not from rounded values.
"""
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats
import config
import scoring
from arms.rescore import ABLATIONS
from eval import metrics as m
from exploratory.noise_floor.analyze import RUNS, boards

HERE = Path(__file__).resolve().parent
FLOOR = 0.062
N_BOOT = 10_000


def main():
    lab = pd.read_csv(config.LABELS_DIR / "panel_labels.csv").set_index("gene_code").sort_index()
    y = lab["label"].values
    pen = {}
    for s, run in RUNS.items():
        sc = pd.read_csv(run / "scores.csv").set_index("gene_code")["score"].reindex(lab.index).values
        iso = pd.Series({c: scoring.score(ABLATIONS["isolated"](a)) for c, a in boards(run).items()}).reindex(lab.index).values
        pen[s] = m.auroc(y, sc) - m.auroc(y, iso)
    d = np.array([pen[s] for s in sorted(pen)])
    n, mean, sd = len(d), d.mean(), d.std(ddof=1)
    se = sd / np.sqrt(n)
    tcrit = stats.t.ppf(0.975, n - 1)
    t_lo, t_hi = mean - tcrit * se, mean + tcrit * se
    t_stat, p_two = stats.ttest_1samp(d, 0.0)
    rng = np.random.default_rng(config.SEED)
    boot = rng.choice(d, size=(N_BOOT, n), replace=True).mean(axis=1)
    b_lo, b_hi = np.percentile(boot, [2.5, 97.5])
    p_sign = 0.5 ** n if (d < 0).all() else None

    text = "\n".join([
        "# Paired analysis of the coordination penalty",
        "",
        "**Post-freeze extension, not pre-registered.** This comparator was chosen after seeing results, consistent "
        "with the multiplicity disclosure in section 7.1 of the report: the secondary contrasts, and now the way the "
        "penalty is tested, were picked after the data were in. Generated by `exploratory/noise_floor/paired.py`.",
        "",
        "## The five replicate-level penalties",
        "",
        "Penalty = A3 AUROC − AUROC of the same board re-scored round 0 only (isolated specialists), per replicate.",
        "",
        "| Seed | Penalty |", "| --- | --- |", *[f"| {s} | {pen[s]:+.4f} |" for s in sorted(pen)],
        "",
        "## Results",
        "",
        "| Statistic | Value |",
        "| --- | --- |",
        f"| n (replicates) | {n} |",
        f"| Mean | **{mean:+.4f}** |",
        f"| SD | {sd:.4f} |",
        f"| Standard error | {se:.4f} |",
        f"| 95% t-interval (df = {n - 1}, t = {tcrit:.3f}) | **{t_lo:+.4f} to {t_hi:+.4f}** |",
        f"| Paired t-test, two-sided (H0: mean penalty = 0) | t = {t_stat:.2f}, **p = {p_two:.4f}** |",
        f"| Paired bootstrap over replicates ({N_BOOT:,} resamples), 95% percentile interval | {b_lo:+.4f} to {b_hi:+.4f} |",
        f"| Sign test | {int((d < 0).sum())}/{n} negative, one-sided p = {p_sign:.3f} |" if p_sign else "| Sign test | not all negative |",
        "",
        "**Fragility, stated.** With n = 5 the t-interval leans on a normality assumption that five points cannot "
        "check, and the bootstrap over five values can only draw from 126 distinct resamples, so its interval is "
        "too narrow rather than too wide. The two agree that the interval excludes zero; neither should be read as "
        "precise. The sign test makes no distributional assumption at all.",
        "",
        "## Why the paired comparator is the right one here",
        "",
        "The coordination penalty compares two scorings of the **same** board: the round-0 verdicts and the final "
        "verdicts after needs, skeptic and revisions. Run-to-run variation (which genes the model happened to rate "
        "higher in a given run) is shared by both sides, so it largely cancels in the difference. The right question "
        "is therefore whether the within-run difference is consistently non-zero across runs, which is what the "
        "paired t-test, the bootstrap and the sign test ask. Comparing it to the 0.062 floor, which measures how much "
        "two **independent** runs disagree, overstates the noise this contrast faces.",
        "",
        "The 0.062 floor still applies to **unpaired** contrasts, where the two sides come from different runs: for "
        "example round 0 vs A1 (+0.080, 1.3× the floor), the Evo 2 runs vs A3, and the constrained planner vs round "
        f"0. Those differences include the full run-to-run variation, so the floor ({FLOOR:.3f}) is the right "
        "yardstick for them.",
        "",
    ])
    (HERE / "PAIRED_ANALYSIS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
