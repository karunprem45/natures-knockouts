"""T2 write-up: A2-constrained vs round 0, A3 and A1 (seed 1). Post-freeze extension, not pre-registered.

  python -m exploratory.A2_constrained.analyze    -> exploratory/A2_constrained/RESULTS.md
"""
import json, re
from collections import Counter
from pathlib import Path
import numpy as np
import pandas as pd
import config
from eval import metrics as m

ROOT = config.ROOT
HERE = Path(__file__).resolve().parent
FR = ROOT / "frozen_results" / "runs"


def fmt(t):
    return f"{t[0]:.3f} ({t[1]:.3f}–{t[2]:.3f})"


def fmtd(t):
    return f"{t[0]:+.3f} ({t[1]:+.3f}, {t[2]:+.3f})"


def scores(path, idx):
    return pd.read_csv(path / "scores.csv").set_index("gene_code")["score"].reindex(idx).values.astype(float)


def main():
    lab = pd.read_csv(config.LABELS_DIR / "panel_labels.csv").set_index("gene_code").sort_index()
    y, idx = lab["label"].values, lab.index
    a2c = scores(HERE, idx)
    ref = {"round 0 (A3_isolated, seed 1)": scores(FR / "A3_isolated_s1", idx),
           "A3 (seed 1)": scores(FR / "A3_s1", idx), "A1 (seed 1)": scores(FR / "A1_s1", idx)}
    plans = json.loads((HERE / "plans.json").read_text())
    pairs = Counter(" + ".join(sorted(p["plan"])) for p in plans)
    status = Counter(p["plan_status"] for p in plans)
    log = [json.loads(l) for l in (HERE / "llm_log.jsonl").read_text().splitlines()]
    calls = [l for l in log if "prompt_tokens" in l]
    floor_md = ROOT / "exploratory/noise_floor/RESULTS.md"
    floor = None
    if floor_md.exists():
        mt = re.search(r"Measured noise floor:\s+([0-9.]+)", floor_md.read_text())
        floor = float(mt.group(1)) if mt else None

    d_r0 = m.paired_delta(m.auroc, y, a2c, ref["round 0 (A3_isolated, seed 1)"])
    per_spec = Counter(s for p in plans for s in p["plan"])
    always = [s for s, n in per_spec.items() if n == len(plans)]
    never = [s for s in config.ACTIVE_EVIDENCE_AGENTS if s not in per_spec]
    always_line = (f"It chose {', '.join(always) or 'no specialist'} for every gene"
                   + (f" and never chose {', '.join(never)}" if never else "")
                   + "; " + ", ".join(f"{s} {n}/{len(plans)}" for s, n in per_spec.most_common()) + ".")
    top_pair, top_n = pairs.most_common(1)[0]
    if top_n >= 0.9 * len(plans):
        outcome = ("Planner picks the same pair every time",
                   f"The planner did not adapt per gene: it chose {top_pair} for {top_n} of {len(plans)} genes, a "
                   "degenerate strategy, reported as such.")
    elif floor is not None and d_r0[0] < -floor:
        outcome = ("A2 well below round 0", "A planner choosing without seeing evidence loses information that "
                   "needs-driven coordination preserves. That is the cost of centralizing the decision.")
    else:
        outcome = ("A2 near round 0", "Two well-chosen specialists capture most of the signal; the remaining channels "
                   "add little on this panel.")
    second = None
    if outcome[0].startswith("Planner picks") and floor is not None:
        second = ("well below round 0" if d_r0[0] < -floor else "near round 0") + \
                 f" (A2-constrained − round 0 = {d_r0[0]:+.3f} against a floor of {floor:.3f})"

    lines = [
        "# A2-constrained: a centralized planner that must choose",
        "",
        "**Post-freeze extension, 1 seed, not pre-registered.** Same model, same 10-call cap, unchanged `scoring.py`. "
        "The planner sees only the gene code and one line per specialist, never evidence, and must pick exactly 2 of "
        "the 4; those 2 run exactly as in A3 round 0. No needs, no skeptic, no revisions. Comparisons use seed 1 of "
        "each frozen arm, the seed this run used. Generated by `exploratory/A2_constrained/analyze.py`.",
        "",
        f"AUROC {fmt(m.bootstrap_ci(m.auroc, y, a2c))} · AUPRC {m.auprc(y, a2c):.3f} · P@12 "
        f"{m.precision_at_k(y, a2c):.2f} · {len(calls)} LLM calls ({np.mean([p['calls'] for p in plans]):.1f} per gene) · "
        f"${sum(l.get('cost_usd') or 0 for l in calls):.2f}",
        "",
        "| Contrast | Paired Δ AUROC (95% CI) |",
        "| --- | --- |",
        *[f"| A2-constrained − {k} | **{fmtd(m.paired_delta(m.auroc, y, a2c, v))}** |" for k, v in ref.items()],
        "",
        "## Which pairs the planner chose",
        "",
        "| Pair | Genes |", "| --- | --- |", *[f"| {k} | {v} |" for k, v in pairs.most_common()],
        "",
        f"Plan validity: {', '.join(f'{k} {v}' for k, v in status.items())}.",
        "",
        f"## Outcome: {outcome[0]}",
        "",
        outcome[1] + (f" On score, it is {second}." if second else ""),
        "",
        (f"Noise floor for comparison: {floor:.3f} AUROC (T1, 5 replicates)." if floor else
         "Noise floor: T1 not finished when this was generated."),
        "",
        f"**Planner behaviour.** {always_line} Because the planner never sees evidence, nothing distinguishes one gene "
        "code from another, so the variation in its second pick cannot reflect the gene. This arm therefore measures "
        "what a mostly fixed two-channel subset, chosen by an uninformed central planner, retains compared with all "
        "four channels.",
        "",
    ]
    (HERE / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
