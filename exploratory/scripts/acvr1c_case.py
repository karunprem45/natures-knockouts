"""P0-1: ACVR1C case file, read entirely from frozen outputs. Post-freeze extension, not pre-registered.

  python -m exploratory.scripts.acvr1c_case

Reads frozen_results/runs/A3_s{1,2}/ (scores and boards), frozen/panel.csv, the local per-agent views
(data/views/, for the blindness check) and the labels (data/labels/, for ranks among negatives).
Writes exploratory/ACVR1C_CASE.md. Writes nothing under frozen/ or frozen_results/.
"""
import csv, json, re, subprocess
from pathlib import Path
import numpy as np
import config

ROOT = config.ROOT
RUNS = ROOT / "frozen_results" / "runs"
OUT = ROOT / "exploratory" / "ACVR1C_CASE.md"
SEEDS = (1, 2)
TARGET = "ACVR1C"
ALSO = ["ZNF229", "PKD1L3"]
AGENTS = ["burden", "gwas", "tolerance", "safety", "variant"]
DRUG_TERMS = ["chembl", "clinical_precedence", "clinicalstage", "clinical_stage", "drug", "approval", "phase_"]


def load_scores(seed):
    with (RUNS / f"A3_s{seed}" / "scores.csv").open() as f:
        return {r["gene_code"]: float(r["score"]) for r in csv.DictReader(f)}


def load_board(seed, code):
    arts = [json.loads(l) for l in (RUNS / f"A3_s{seed}" / "board.jsonl").read_text().splitlines()]
    return [a for a in arts if a["gene_code"] == code]


def ranks(scores, codes):
    """Standard competition rank (1 = highest score); ties share the best rank."""
    vals = {c: scores[c] for c in codes}
    return {c: 1 + sum(v > vals[c] for v in vals.values()) for c in codes}


def main():
    with (config.LABELS_DIR / "panel_labels.csv").open() as f:
        labels = {r["gene_code"]: r for r in csv.DictReader(f)}
    with (config.FROZEN_DIR / "panel.csv").open() as f:
        ensembl = {r["gene_code"]: r["ensembl_id"] for r in csv.DictReader(f)}
    sym2code = {r["symbol"]: c for c, r in labels.items()}
    codes = sorted(labels)
    negs = [c for c in codes if labels[c]["label"] == "0"]

    per_seed = {s: load_scores(s) for s in SEEDS}
    mean = {c: float(np.mean([per_seed[s][c] for s in SEEDS])) for c in codes}
    rank_tables = {"mean": (ranks(mean, codes), ranks(mean, negs))}
    for s in SEEDS:
        rank_tables[f"seed {s}"] = (ranks(per_seed[s], codes), ranks(per_seed[s], negs))

    def rank_rows(sym):
        c = sym2code[sym]
        rows = []
        for name, (all_r, neg_r) in rank_tables.items():
            score = mean[c] if name == "mean" else per_seed[int(name.split()[1])][c]
            rows.append(f"| {name} | {score:+.3f} | {all_r[c]} / 40 | {neg_r[c]} / 28 |")
        return rows

    code = sym2code[TARGET]
    L = ["# ACVR1C case file",
         "",
         "**Post-freeze extension, not pre-registered.** Every number below is read from frozen outputs "
         "(`frozen_results/runs/A3_s1`, `A3_s2`); no arm was re-run or re-scored. Generated by "
         "`exploratory/scripts/acvr1c_case.py`.",
         "",
         f"ACVR1C is **{code}** on the blind panel and was labelled a **negative**: it has in-scope protective "
         "loss-of-function burden evidence but no in-scope drug evidence, which is how `build_labels.py` defines a "
         "negative. The agents only ever saw the code.",
         "",
         "## 1. Rank in frozen A3",
         "",
         "Rank 1 = most promising. Ties share the best rank. \"mean\" averages the two seeds' scores, as the frozen "
         "arms table does.",
         "",
         "| A3 run | Score | Rank among all genes | Rank among negatives |",
         "| --- | --- | --- | --- |", *rank_rows(TARGET), ""]

    L += ["## 2. Per-channel verdicts from the saved A3 boards", ""]
    for s in SEEDS:
        board = load_board(s, code)
        by_id = {a["artifact_id"]: a for a in board}
        superseded = {p for a in board if a["artifact_type"] == "revision" for p in a["parent_artifact_ids"]}
        latest = {}
        for a in sorted(board, key=lambda a: (a["round"], a["timestamp"])):
            if a["artifact_type"] in ("evidence", "revision") and a["artifact_id"] not in superseded:
                latest[a["producer_agent"]] = a
        challenged = {c["channel"] for a in board if a["artifact_type"] == "challenge" for c in a["challenges"]}
        L += [f"**Seed {s}** (final score {per_seed[s][code]:+.3f})", "",
              "| Channel | Round 0 verdict | Final verdict | Skeptic discount | Final rationale |",
              "| --- | --- | --- | --- | --- |"]
        for ag in AGENTS[:4]:
            r0 = next((a for a in board if a["producer_agent"] == ag and a["artifact_type"] == "evidence"), None)
            fin = latest.get(ag)
            v0 = f"{r0['stance']} {r0['strength']:.2f}" if r0 else "-"
            vf = f"{fin['stance']} {fin['strength']:.2f}" + (" (revised)" if fin and fin["artifact_type"] == "revision" else "") if fin else "-"
            why = (fin["rationale"] if fin else "").replace("|", "/")
            L.append(f"| {ag} | {v0} | {vf} | {'x0.5' if ag in challenged else 'none'} | {why} |")
        L.append("")

    L += ["## 3. Provenance chain", "",
          "Every artifact on the board for this gene, in round order. IDs are the first 8 characters of each "
          "artifact's UUID; parents point to earlier artifacts.", ""]
    for s in SEEDS:
        board = sorted(load_board(s, code), key=lambda a: (a["round"], a["timestamp"]))
        by_id = {a["artifact_id"]: a for a in board}
        short = lambda i: i[:8]
        L += [f"**Seed {s}**: {len(board)} artifacts", "",
              "| ID | Round | Type | Agent | Verdict | Parents | Needs raised / challenges |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
        for a in board:
            parents = ", ".join(f"{short(p)} ({by_id[p]['producer_agent']})" for p in a["parent_artifact_ids"] if p in by_id) or "-"
            if a["artifact_type"] == "challenge":
                extra = "; ".join(f"{c['type']} on {c['channel']}" for c in a["challenges"]) or "no challenges"
                verdict = "-"
            else:
                extra = "; ".join(f"{n['type']}: {n['query'][:70]}" for n in a["needs"]) or "-"
                verdict = f"{a['stance']} {a['strength']:.2f}"
            if a["artifact_type"] == "fulfillment":
                req = by_id.get(a["parent_artifact_ids"][0], {}).get("producer_agent", "?")
                extra = f"answered a need raised by {req}"
            L.append(f"| {short(a['artifact_id'])} | {a['round']} | {a['artifact_type']} | {a['producer_agent']} | "
                     f"{verdict} | {parents} | {extra.replace('|', '/')} |")
        L.append("")

    # 4. blindness proof
    raw = json.loads((config.RAW_DIR / f"{ensembl[code]}.json").read_text())
    ident = raw["identity"]
    terms = sorted({ident["symbol"], ensembl[code], ident["name"] or "", *ident["synonyms"]} - {""}, key=str.lower)
    hits = []
    view_files = []
    for ag in AGENTS:
        p = config.VIEWS_DIR / ag / f"{code}.json"
        if not p.exists():
            continue
        view_files.append(p)
        text = p.read_text()
        low = text.lower()
        for t in terms:
            if re.search(rf"(?<![A-Za-z0-9]){re.escape(t.lower())}(?![A-Za-z0-9])", low):
                hits.append(f"{ag}: identity term {t!r}")
        for d in DRUG_TERMS:
            if d in low:
                hits.append(f"{ag}: drug term {d!r}")
    flagged = [a for s in SEEDS for a in load_board(s, code) if any(f.startswith("identity_named") for f in a["flags"])]
    test = subprocess.run([str(ROOT / ".venv" / "bin" / "python"), "-m", "pytest", "-q",
                           "tests/test_views_isolation.py", "-k", code],
                          cwd=ROOT, capture_output=True, text=True)
    test_line = test.stdout.strip().splitlines()[-1] if test.stdout.strip() else test.stderr.strip()[-200:]

    L += ["## 4. Proof of blindness", "",
          f"Checked {len(view_files)} view files (`data/views/<agent>/{code}.json`) for {len(terms)} identity terms "
          f"(symbol, Ensembl ID, approved name and every synonym) and {len(DRUG_TERMS)} drug-evidence terms, "
          "case-insensitive, whole-word.", "",
          f"- Identity or drug terms found: **{len(hits)}**" + (f" ({'; '.join(hits)})" if hits else ""),
          f"- Identity terms checked: {', '.join(f'`{t}`' for t in terms)}",
          f"- A3 artifacts for {code} flagged for naming a gene (output redaction): **{len(flagged)}**",
          f"- Isolation test covering these files: `tests/test_views_isolation.py` (parametrised per view, "
          f"`test_view[<agent>/{code}]`, plus `test_safety_view_holds_no_mendelian_disease_names`). "
          f"Run now with `-k {code}`: **{test_line}**",
          "- The views are local working files (`data/` is gitignored); the test and this script regenerate the "
          "check from them.", ""]

    L += ["## 5. The other two top-ranked negatives", "",
          "**Hypotheses only.** Their literature has not been checked, so no biological claim is made.", ""]
    for sym in ALSO:
        L += [f"**{sym}** ({sym2code[sym]})", "", "| A3 run | Score | Rank among all genes | Rank among negatives |",
              "| --- | --- | --- | --- |", *rank_rows(sym), ""]

    L += ["## 6. Published evidence for ACVR1C", "",
          "Emdin CA et al. DNA sequence variation in ACVR1C encoding the activin receptor-like kinase 7 influences "
          "body fat distribution and protects against type 2 diabetes. *Diabetes* 2019;68(1):226–234. "
          "doi:10.2337/db18-0857.", "",
          "- Exome-wide association study of coding variation in 405,569 UK Biobank participants: four ACVR1C "
          "variants lowered waist-to-hip ratio adjusted for BMI. Pooled, a 0.2 SD decrease through ACVR1C was "
          "associated with **30% lower type 2 diabetes risk** (OR 0.70, 95% CI 0.63–0.77, P = 5.6 × 10⁻¹³).",
          "- In a separate exome-sequencing analysis of 55,516 people, carriers of predicted damaging ACVR1C variants "
          "had **54% lower type 2 diabetes risk** (OR 0.46, 95% CI 0.27–0.81).",
          "- The authors conclude that predicted loss-of-function variants in ACVR1C protect against type 2 diabetes.",
          "",
          "## What this does and does not show", "",
          "- It shows the collective ranked, blind, a gene with published protective loss-of-function evidence at the "
          "top of the genes our panel called negative.",
          "- It does not show prospective discovery: the evidence is in Open Targets, which the agents read, and "
          "the 2019 paper predates the run. The claim is \"surfaced blind from anonymised evidence\", not \"discovered\".",
          "- ACVR1C's high rank in A3 is one gene; on its own it is a case study, not a statistic.",
          f"- **The rank depends on the seed.** ACVR1C is the top negative only on the seed-averaged score. Seed 1: "
          f"{rank_tables['seed 1'][0][code]}/40 overall, {rank_tables['seed 1'][1][code]}/28 among negatives. Seed 2: "
          f"{rank_tables['seed 2'][0][code]}/40, {rank_tables['seed 2'][1][code]}/28. The top three negatives are "
          f"close: {mean[sym2code['ACVR1C']]:+.3f}, {mean[sym2code['ZNF229']]:+.3f}, {mean[sym2code['PKD1L3']]:+.3f}.",
          "- **The seed-2 drop is the skeptic.** In seed 2 it fired `biomarker_only` on burden and GWAS, halving both "
          "channels; in seed 1 it raised no challenge. That is the failure mode in `frozen_results/FINDINGS.md` §2, "
          "acting on a gene with published protective evidence.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    print("\n".join(L[:22]))
    print("... blindness:", len(hits), "hits;", test_line)


if __name__ == "__main__":
    main()
