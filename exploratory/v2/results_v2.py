"""P2-1 step 5: score the panel-2 board three ways and report the pre-registered contrasts.

  python -m exploratory.v2.results_v2     -> exploratory/v2/RESULTS_V2.md, exploratory/v2/scores_v2.csv
"""
import json
from pathlib import Path
import numpy as np
import pandas as pd
import config
import scoring
from arms.rescore import ABLATIONS
from board.artifact import Artifact
from eval import metrics as m
from exploratory.v2 import scoring_v2

HERE = Path(__file__).resolve().parent
RUN = HERE / "runs" / "A3_v2_s1"
NOISE_FLOOR = 0.03


def fmt(t):
    return f"{t[0]:.3f} ({t[1]:.3f}–{t[2]:.3f})"


def fmtd(t):
    return f"{t[0]:+.3f} ({t[1]:+.3f}, {t[2]:+.3f})"


def main():
    lab = pd.read_csv(config.LABELS_DIR / "panel2_labels.csv").set_index("gene_code").sort_index()
    y = lab["label"].values
    boards = {}
    for p in sorted((RUN / "genes").glob("Gene_*.json")):
        rec = json.loads(p.read_text())
        boards[rec["gene_code"]] = [Artifact.from_dict(a) for a in rec["artifacts"]]
    assert set(boards) == set(lab.index), "panel-2 run is incomplete"
    df = pd.DataFrame({
        "A3_v2_calibrated": {c: scoring_v2.score(a) for c, a in boards.items()},
        "A3_v2_flat": {c: scoring.score(a) for c, a in boards.items()},
        "A3_v2_round0": {c: scoring.score(ABLATIONS["isolated"](a)) for c, a in boards.items()},
    }).reindex(lab.index)
    df.to_csv(HERE / "scores_v2.csv", index_label="gene_code")
    s = {k: df[k].values for k in df.columns}
    errors = sum(a.artifact_type == "error" for arts in boards.values() for a in arts)

    arm_rows = [f"| {k} | {fmt(m.bootstrap_ci(m.auroc, y, v))} | {m.auprc(y, v):.3f} | {m.precision_at_k(y, v):.2f} |"
                for k, v in s.items()]
    prim = m.paired_delta(m.auroc, y, s["A3_v2_calibrated"], s["A3_v2_flat"])
    cal_r0 = m.paired_delta(m.auroc, y, s["A3_v2_calibrated"], s["A3_v2_round0"])
    flat_r0 = m.paired_delta(m.auroc, y, s["A3_v2_flat"], s["A3_v2_round0"])

    # prereg_v2.md named three outcomes but set no threshold for "improvement". The conservative reading used
    # here (decided when the results were read, and stated in the report): an improvement must exceed the
    # measured run-to-run noise floor and its interval must exclude zero.
    improved = prim[0] > NOISE_FLOOR and prim[1] > 0
    if improved and cal_r0[0] >= -NOISE_FLOOR:
        outcome = ("Calibrated > flat, approaching round 0",
                   "The diagnosed failure was fixed by a pre-registered correction on genes it never saw.")
    elif improved:
        outcome = ("Calibrated > flat, still below round 0",
                   "Calibration helps but does not close the gap; here a skeptic costs more than it returns.")
    else:
        outcome = ("No improvement",
                   "The problem is not calibration; skeptic-style self-critique does not pay on this task.")
    sig = "excludes" if prim[1] > 0 or prim[2] < 0 else "includes"

    challenges = [c["type"] for arts in boards.values() for a in arts if a.artifact_type == "challenge" for c in a.challenges]
    from collections import Counter
    ctab = Counter(challenges).most_common()
    log = [json.loads(l) for l in (RUN / "llm_log.jsonl").read_text().splitlines()]
    calls = [l for l in log if "prompt_tokens" in l]

    text = "\n".join([
        "# Results v2: calibrated skeptic on a fresh panel",
        "",
        "**Post-freeze extension.** Pre-registered in [`prereg_v2.md`](prereg_v2.md), tagged `prereg-v2` before "
        "panel 2 was built. Generated by `exploratory/v2/results_v2.py`.",
        "",
        f"Panel 2: 12 positives (shared with panel 1) and 28 fresh negatives, coded Gene_41 to Gene_80. Isolation "
        f"test on the panel-2 views: 203 checks passed. One A3 run, seed 1: {len(calls)} LLM calls, {errors} error "
        f"artifacts, ${sum(l.get('cost_usd') or 0 for l in calls):.2f}. The same board is scored three ways.",
        "",
        "| Scoring of the one panel-2 board | AUROC (95% CI) | AUPRC | P@12 |",
        "| --- | --- | --- | --- |",
        *arm_rows,
        "",
        "| Contrast | Paired Δ AUROC (95% CI) |",
        "| --- | --- |",
        f"| **Primary: calibrated − flat** | **{fmtd(prim)}** |",
        f"| Calibrated − round 0 | {fmtd(cal_r0)} |",
        f"| Flat − round 0 | {fmtd(flat_r0)} |",
        "",
        f"## Outcome (pre-registered wording): {outcome[0]}",
        "",
        outcome[1],
        "",
        f"The primary interval {sig} zero, and the point estimate ({prim[0]:+.3f}) is well inside the "
        f"{NOISE_FLOOR:.2f} AUROC noise floor between two runs of one configuration (A2 rerun on panel 1). "
        "`prereg_v2.md` named the three outcomes but set no threshold for \"improvement\"; the rule applied here, "
        "decided when the results were read, is the conservative one: an improvement must exceed the noise floor "
        "and its interval must exclude zero. Under the lenient alternative (any positive point estimate) this run "
        "would have read as \"calibrated > flat\", which the data do not support.",
        "",
        "*Note added after T1:* the noise floor was later measured over five replicates of A3 as 0.062 AUROC "
        "(`exploratory/noise_floor/RESULTS.md`). The 0.03 above is the single-pair estimate available when this was "
        "first written. Against 0.062 the primary contrast (+0.004) is even further inside the floor; the "
        "conclusion is unchanged.",
        "",
        "## Why so little room",
        "",
        f"Panel 2 is much easier than panel 1: round 0 scores {m.auroc(y, s['A3_v2_round0']):.3f} here against "
        "0.853 on panel 1, so the fresh negatives are easier to separate from the shared positives. The flat "
        f"skeptic's cost shrank with it, {flat_r0[0]:+.3f} here against −0.071 on panel 1, leaving calibration little "
        "to recover. `biomarker_only` is again the most frequent challenge and calibration now ignores it, yet the "
        "score barely moves. The same direction as panel 1 holds: the skeptic loop scores at or below the "
        "isolated specialists on both panels.",
        "",
        "Skeptic challenges on panel 2: " + ", ".join(f"{t} {n}" for t, n in ctab) + ".",
        "",
        "## Disclosed",
        "",
        "Panel 2 shares the 12 positives; only the negatives are fresh. The multipliers were fitted on panel 1 and "
        "frozen before panel 2 existed. One parameter set was fitted; no agent was trained. One seed.",
        "",
    ])
    (HERE / "RESULTS_V2.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
